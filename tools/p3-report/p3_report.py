"""Combine the testers' shared usage numbers into the P3 gate numbers (SPEC-stability.md).

Save each report a tester sends as a text file named after the tester, e.g. reports/T3-day7.txt
(the text can be pasted straight from the email, quoting and all). Then run:

    python3 -I tools/p3-report/p3_report.py [--days N] [reports_dir] [out.md]

Defaults: tools/p3-report/reports/ and docs/p3-results.md. --days is how long the closed test has run.
The reports folder is git-ignored; only the aggregate results file is committed. Standard library only.
"""
import os
import re
import sys

GATE_PCT = 99.0
MIN_TESTERS = 10
MIN_DAYS = 14

INT_FIELDS = {
    "Sessions": "sessions",
    "Crash-free sessions": "crash_free",
    "Crashes": "crashes",
    "ANRs": "anrs",
    "Low-memory kills": "low_memory",
    "Messages": "messages",
    "Talks": "talks",
    "Memories saved": "memories",
}
TESTER = re.compile(r"^(T\d+)\b")


class Malformed(ValueError):
    pass


def parse(text):
    """One report's numbers. Raises Malformed if a needed line is missing or not a number."""
    fields = {}
    for line in text.splitlines():
        line = line.lstrip("> ").strip()
        if ": " in line:
            key, value = line.split(": ", 1)
            fields.setdefault(key, value.strip())
    r = {}
    try:
        for key, name in INT_FIELDS.items():
            r[name] = int(fields[key])
        r["version"] = fields["App version"]
        r["model"] = fields["Phone"].rsplit(", Android", 1)[0]
        days = re.match(r"(\d+) \((\d+) in the first 14 days\)", fields["Active days"])
        if not days:
            raise Malformed("Active days line not understood")
        r["active_days"], r["first14"] = int(days[1]), int(days[2])
        r["day7"] = fields["Used on day 7 or later"] == "yes"
        actions = fields["Actions"]
        r["actions"] = {} if actions == "none" else {
            name: int(n) for name, n in (a.rsplit(" ", 1) for a in actions.split(", "))
        }
    except KeyError as e:
        raise Malformed(f"missing line: {e.args[0]}")
    except ValueError as e:
        raise Malformed(str(e))
    if r["crash_free"] > r["sessions"]:
        raise Malformed("more crash-free sessions than sessions")
    return r


def load(folder):
    """({tester: latest report}, [(file, reason)]). The latest is the one with the most sessions (counts only grow)."""
    latest, skipped = {}, []
    for name in sorted(os.listdir(folder)):
        path = os.path.join(folder, name)
        if not os.path.isfile(path) or name.startswith("."):
            continue
        tester = TESTER.match(name)
        if not tester:
            skipped.append((name, "no tester id (name it T<n>-…)"))
            continue
        try:
            with open(path, encoding="utf-8") as f:
                r = parse(f.read())
        except (Malformed, UnicodeDecodeError) as e:
            skipped.append((name, str(e)))
            continue
        t = tester[1]
        if t not in latest or r["sessions"] >= latest[t]["sessions"]:
            latest[t] = r
    return latest, skipped


def summarize(latest):
    rs = list(latest.values())
    sessions = sum(r["sessions"] for r in rs)
    crash_free = sum(r["crash_free"] for r in rs)
    by_model = {}
    for r in rs:
        s, c = by_model.get(r["model"], (0, 0))
        by_model[r["model"]] = (s + r["sessions"], c + r["crash_free"])
    actions = {}
    for r in rs:
        for k, v in r["actions"].items():
            actions[k] = actions.get(k, 0) + v
    return {
        "testers": len(rs),
        "sessions": sessions,
        "crash_free": crash_free,
        "crash_free_pct": 100.0 * crash_free / sessions if sessions else None,
        "crashes": sum(r["crashes"] for r in rs),
        "anrs": sum(r["anrs"] for r in rs),
        "low_memory": sum(r["low_memory"] for r in rs),
        "day7_testers": sum(1 for r in rs if r["day7"]),
        "first14": sorted(r["first14"] for r in rs),
        "by_model": by_model,
        "features": {k: sum(r[k] for r in rs) for k in ("messages", "talks", "memories")},
        "actions": actions,
        "versions": sorted({r["version"] for r in rs}),
        "per_tester": {t: (r["sessions"], r["crash_free"], r["first14"], r["day7"]) for t, r in sorted(latest.items())},
    }


def markdown(s, skipped, days):
    out = ["# P3 closed-test results", "",
           "Generated by `tools/p3-report/p3_report.py` from the usage numbers testers shared. "
           "Testers are T1…Tn; no names, emails or content.", ""]
    if not s["testers"]:
        out += ["No reports yet."]
    else:
        pct = s["crash_free_pct"]
        verdict = "**PASS**" if pct is not None and pct >= GATE_PCT else "**FAIL**"
        n = s["testers"]
        out += [
            "## Gate (PRD 0.6: crash-free sessions ≥ 99 % in the core loop)",
            f"- Crash-free sessions: **{pct:.1f} %** ({s['crash_free']} of {s['sessions']} sessions, "
            f"{n} tester{'s' if n != 1 else ''}) → {verdict}" if pct is not None
            else f"- No sessions in {n} report(s) → **FAIL**",
            f"- Crashes {s['crashes']}, ANRs {s['anrs']}; low-memory kills {s['low_memory']} (not counted as crashes).",
            f"- App versions in the reports: {', '.join(s['versions'])}.",
        ]
        caveats = []
        if n < MIN_TESTERS:
            caveats.append(f"Based on fewer than {MIN_TESTERS} testers.")
        if days is None:
            caveats.append("Test length not given (run with --days N).")
        elif days < MIN_DAYS:
            caveats.append(f"The test has run {days} days, under {MIN_DAYS} days.")
        out += [f"- Caveat: {c}" for c in caveats]
        out += ["", "## Retention signal",
                f"- Used on day 7 or later: {s['day7_testers']} of {n} testers.",
                f"- Active days in the first 14 days, per tester (sorted): {', '.join(map(str, s['first14']))}.",
                "", "## By phone", "| Phone | Sessions | Crash-free | % |", "|---|---|---|---|"]
        for model, (ses, cf) in sorted(s["by_model"].items()):
            out.append(f"| {model} | {ses} | {cf} | {100.0 * cf / ses:.1f} |" if ses else f"| {model} | 0 | 0 | – |")
        f = s["features"]
        acts = ", ".join(f"{k} {v}" for k, v in sorted(s["actions"].items())) or "none"
        out += ["", "## What testers used",
                f"- Messages {f['messages']}, talks {f['talks']}, memories saved {f['memories']}.",
                f"- Actions: {acts}.",
                "", "## Per tester", "| Tester | Sessions | Crash-free | Days in first 14 | Day 7+ |", "|---|---|---|---|---|"]
        for t, (ses, cf, d14, d7) in s["per_tester"].items():
            out.append(f"| {t} | {ses} | {cf} | {d14} | {'yes' if d7 else 'no'} |")
    if skipped:
        out += ["", "## Skipped files"] + [f"- `{name}`: {why}" for name, why in skipped]
    return "\n".join(out) + "\n"


def main(argv):
    days = None
    if "--days" in argv:
        i = argv.index("--days")
        days = int(argv[i + 1])
        argv = argv[:i] + argv[i + 2:]
    here = os.path.dirname(os.path.abspath(__file__))
    folder = argv[0] if argv else os.path.join(here, "reports")
    out = argv[1] if len(argv) > 1 else os.path.join(here, "..", "..", "docs", "p3-results.md")
    latest, skipped = load(folder) if os.path.isdir(folder) else ({}, [])
    for name, why in skipped:
        print(f"skipped {name}: {why}", file=sys.stderr)
    with open(out, "w", encoding="utf-8") as f:
        f.write(markdown(summarize(latest), skipped, days))
    print(f"wrote {os.path.normpath(out)} ({len(latest)} testers)")


if __name__ == "__main__":
    main(sys.argv[1:])
